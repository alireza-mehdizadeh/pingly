/** Every kind of interaction. `wire` is the server's event type. */
enum class EventType(val wire: String, val title: String) {
    Ping("ping", "پینگ"),
    Vibrate("vibrate", "لرزش"),
    Sound("sound", "صدا"),
    Voice("voice", "صدای من"),
    Image("image", "عکس"),
    Message("message", "پیام عاشقانه"),
    Question("question", "سؤال"),
    Answer("answer", "جواب");

    /** Instant actions — they only make sense right away. */
    val isInstant: Boolean get() = this == Ping || this == Vibrate || this == Sound || this == Voice

    companion object {
        fun fromWire(value: String): EventType? = entries.firstOrNull { it.wire == value }
    }
}

