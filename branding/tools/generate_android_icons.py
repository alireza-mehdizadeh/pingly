#!/usr/bin/env python3
"""Generates Pingly's Android vector drawables from the brand geometry.

The paths are the same ones used in branding/logo/*.svg (100-unit canvas), so the launcher icon,
the in-app mark, the mascots and the notification icon can never drift from the logo.

    python3 branding/tools/generate_android_icons.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "android/app/src/main/res/drawable"

PI_BODY = ("M50,50 C50.6,40.5 50.2,31.5 48.3,26 C45.8,18.6 40.6,14.5 33.6,14.5 C21.6,14.5 12,24.4 12,38 "
           "C12,56.5 29.5,73 41.6,82.6 C44.6,85 48.4,84.6 49.2,81.2 C50.6,74.5 50.6,62 50,50 Z")
LY_BODY = ("M50,50 C49.4,40.5 49.8,31.5 51.7,26 C54.2,18.6 59.4,14.5 66.4,14.5 C78.4,14.5 88,24.4 88,38 "
           "C88,56.5 70.5,73 58.4,82.6 C55.4,85 51.6,84.6 50.8,81.2 C49.4,74.5 49.4,62 50,50 Z")
PI_GLOSS = "M19.5,30 C21.5,24 26.5,20.4 32,20"
LY_GLOSS = "M68,20 C73.5,20.4 78.5,24 80.5,30"
PI_EYES = ["M27.5,40 q3.2,-3.6 6.4,0", "M38.5,40.8 q3.2,-3.6 6.4,0"]
LY_EYES = ["M55.1,40.8 q3.2,-3.6 6.4,0", "M66.1,40 q3.2,-3.6 6.4,0"]
PI_SMILE = "M34.6,47.4 q2.3,2.4 4.6,0"
LY_SMILE = "M60.8,47.4 q2.3,2.4 4.6,0"
BURST = ["M50,13 L50,6.5", "M42.6,14.4 L39.4,9", "M57.4,14.4 L60.6,9"]

INK = "#FF3D2645"
BUTTER = "#FFFFC24B"


def ellipse(cx, cy, rx, ry):
    return f"M{cx - rx},{cy} a{rx},{ry} 0 1,0 {2 * rx},0 a{rx},{ry} 0 1,0 {-2 * rx},0 Z"


PI_BLUSH = ellipse(26.5, 47, 3.8, 2.4)
LY_BLUSH = ellipse(73.5, 47, 3.8, 2.4)


def gradient_fill(path, start, end, c0, c1):
    return f'''    <path android:pathData="{path}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="{start[0]}" android:startY="{start[1]}"
                android:endX="{end[0]}" android:endY="{end[1]}">
                <item android:offset="0" android:color="{c0}" />
                <item android:offset="1" android:color="{c1}" />
            </gradient>
        </aapt:attr>
    </path>
'''


def fill(path, color, alpha=None):
    a = f' android:fillAlpha="{alpha}"' if alpha is not None else ""
    return f'    <path android:pathData="{path}" android:fillColor="{color}"{a} />\n'


def stroke(path, color, width, alpha=None):
    a = f' android:strokeAlpha="{alpha}"' if alpha is not None else ""
    return (f'    <path android:pathData="{path}" android:strokeColor="{color}" android:strokeWidth="{width}"'
            f' android:strokeLineCap="round" android:strokeLineJoin="round"{a} />\n')


def pi_parts():
    s = gradient_fill(PI_BODY, (12, 14.5), (42.9, 85), "#FFFF9BB3", "#FFFF5C86")
    s += stroke(PI_GLOSS, "#FFFFFFFF", 3.2, 0.65)
    s += "".join(stroke(e, INK, 3) for e in PI_EYES)
    s += stroke(PI_SMILE, INK, 2.4)
    s += fill(PI_BLUSH, "#FFFFFFFF", 0.5)
    return s


def ly_parts():
    s = gradient_fill(LY_BODY, (88, 14.5), (57.1, 85), "#FFC2B6FF", "#FF8B78F4")
    s += stroke(LY_GLOSS, "#FFFFFFFF", 3.2, 0.55)
    s += "".join(stroke(e, INK, 3) for e in LY_EYES)
    s += stroke(LY_SMILE, INK, 2.4)
    s += fill(LY_BLUSH, "#FFFFFFFF", 0.5)
    return s


def burst(color=BUTTER, width=3.2):
    return "".join(stroke(b, color, width) for b in BURST)


def vector(body, size_dp=100, viewport=100, aapt=True):
    ns = ' xmlns:aapt="http://schemas.android.com/aapt"' if aapt else ""
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by branding/tools/generate_android_icons.py — do not edit by hand. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}\n'
            f'    android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
            f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n'
            f'{body}</vector>\n')


def group(inner, tx, ty, scale):
    indented = "".join("    " + line + "\n" for line in inner.splitlines())
    return (f'    <group android:translateX="{tx}" android:translateY="{ty}"'
            f' android:scaleX="{scale}" android:scaleY="{scale}">\n{indented}    </group>\n')


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    mark = pi_parts() + ly_parts() + burst()
    files = {
        # In-app logo, mascots and the burst on the 100-unit brand canvas.
        "ic_pingly_mark.xml": vector(mark),
        "ic_mascot_pi.xml": vector(pi_parts()),
        "ic_mascot_ly.xml": vector(ly_parts()),
        "ic_ping_burst.xml": vector(burst(), aapt=False),
        # Adaptive icon layers on the 108-unit canvas (66-unit safe zone).
        "ic_launcher_foreground.xml": vector(group(mark, 20, 22.9, 0.68), 108, 108),
        "ic_launcher_background.xml": vector(
            gradient_fill("M0,0 h108 v108 h-108 Z", (0, 0), (108, 108), "#FFFFF7F3", "#FFFFE0EA")
            + fill("M-6,88 a26,26 0 1,0 52,0 a26,26 0 1,0 -52,0 Z", "#FFFFFFFF", 0.35)
            + fill("M74,16 a18,18 0 1,0 36,0 a18,18 0 1,0 -36,0 Z", "#FFFFFFFF", 0.35),
            108, 108),
        "ic_launcher_monochrome.xml": vector(group(
            stroke(PI_BODY, "#FF000000", 4.2) + stroke(LY_BODY, "#FF000000", 4.2)
            + "".join(stroke(p, "#FF000000", 3) for p in PI_EYES + LY_EYES + [PI_SMILE, LY_SMILE])
            + "".join(stroke(b, "#FF000000", 3.6) for b in BURST),
            20, 22.9, 0.68), 108, 108, aapt=False),
        # Status-bar icon: white silhouette only (Android tints it).
        "ic_stat_pingly.xml": vector(
            fill(PI_BODY, "#FFFFFFFF") + fill(LY_BODY, "#FFFFFFFF") + burst("#FFFFFFFF", 5.5),
            24, 100, aapt=False),
    }
    for name, content in files.items():
        (OUT / name).write_text(content, encoding="utf-8")
        print("wrote", OUT / name)


if __name__ == "__main__":
    main()
